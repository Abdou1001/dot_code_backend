CREATE TABLE IF NOT EXISTS public.doctor_booking_notification_outbox (
    outbox_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id bigint NOT NULL REFERENCES public.appointment(appointment_id),
    user_id bigint NOT NULL REFERENCES public."user"(user_id),
    doctor_id bigint NOT NULL REFERENCES public.doctor(doctor_id),
    notification_id bigint REFERENCES public.notifications(notification_id),
    channel text NOT NULL CHECK (channel IN ('push', 'sms')),
    phone_number text,
    notification_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'sent')),
    attempts integer NOT NULL DEFAULT 0,
    available_at timestamptz NOT NULL DEFAULT now(),
    locked_at timestamptz,
    lease_token text,
    sent_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT doctor_booking_notification_outbox_appointment_channel_key
        UNIQUE (appointment_id, channel)
);

CREATE INDEX IF NOT EXISTS doctor_booking_notification_outbox_pending_idx
    ON public.doctor_booking_notification_outbox (status, available_at, outbox_id);

ALTER TABLE public.doctor_booking_notification_outbox ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.toggle_doctor_booking(
    p_user_id bigint,
    p_reopen_date date DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_doctor_id bigint;
    v_doctor_status text;
    v_user_role text;
    v_user_status text;
    v_is_booking_open boolean;
    v_booking_reopen_at timestamptz;
    v_today date := (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Aden')::date;
    v_cancelled_count integer := 0;
    v_queued_count integer := 0;
BEGIN
    SELECT
        doctor.doctor_id,
        doctor.status,
        doctor.is_booking_open,
        doctor.booking_reopen_at,
        "user".role,
        "user".is_active
    INTO
        v_doctor_id,
        v_doctor_status,
        v_is_booking_open,
        v_booking_reopen_at,
        v_user_role,
        v_user_status
    FROM public.doctor AS doctor
    JOIN public."user" AS "user"
        ON "user".user_id = doctor.user_id
    WHERE doctor.user_id = p_user_id
    FOR UPDATE OF doctor;

    IF NOT FOUND OR v_user_role <> 'doctor' THEN
        RAISE EXCEPTION 'DOCTOR_BOOKING_ACCOUNT_NOT_FOUND';
    END IF;

    IF v_user_status <> 'active' OR v_doctor_status <> 'active' THEN
        RAISE EXCEPTION 'DOCTOR_ACCOUNT_INACTIVE';
    END IF;

    -- 1. Expired temporary closures become effectively open under the row lock.
    IF NOT COALESCE(v_is_booking_open, true)
        AND v_booking_reopen_at IS NOT NULL
        AND v_booking_reopen_at <= CURRENT_TIMESTAMP THEN
        UPDATE public.doctor
        SET is_booking_open = true,
            booking_reopen_at = NULL
        WHERE doctor_id = v_doctor_id;

        v_is_booking_open := true;
        v_booking_reopen_at := NULL;
    END IF;

    -- 2. A currently closed Doctor can only reopen with an empty request body.
    IF NOT COALESCE(v_is_booking_open, true) THEN
        IF p_reopen_date IS NOT NULL THEN
            RAISE EXCEPTION 'REOPEN_DATE_NOT_ALLOWED';
        END IF;

        UPDATE public.doctor
        SET is_booking_open = true,
            booking_reopen_at = NULL
        WHERE doctor_id = v_doctor_id;

        RETURN jsonb_build_object(
            'doctor_id', v_doctor_id,
            'is_booking_open', true,
            'booking_reopen_at', NULL,
            'cancelled_appointments_count', 0,
            'notifications_queued_count', 0
        );
    END IF;

    -- 3. A temporary closure cannot end before today's Yemen calendar date.
    IF p_reopen_date IS NOT NULL AND p_reopen_date < v_today THEN
        RAISE EXCEPTION 'BOOKING_REOPEN_DATE_IN_PAST';
    END IF;

    UPDATE public.doctor
    SET is_booking_open = false,
        booking_reopen_at = CASE
            WHEN p_reopen_date IS NULL THEN NULL
            ELSE ((p_reopen_date + 1)::timestamp AT TIME ZONE 'Asia/Aden')
        END
    WHERE doctor_id = v_doctor_id
    RETURNING booking_reopen_at INTO v_booking_reopen_at;

    -- 4. Lock and cancel only the exact pending and approved appointments in scope.
    WITH eligible AS (
        SELECT
            appointment.appointment_id,
            appointment.user_id,
            COALESCE(patient.phone_number, appointment.patient_phone) AS phone_number
        FROM public.appointment AS appointment
        JOIN public.doctor_schedule AS schedule
            ON schedule.schedule_id = appointment.schedule_id
        LEFT JOIN public."user" AS patient
            ON patient.user_id = appointment.user_id
        WHERE schedule.doctor_id = v_doctor_id
            AND appointment.status IN ('pending', 'approved')
            AND appointment.appointment_date >= v_today
            AND (
                p_reopen_date IS NULL
                OR appointment.appointment_date <= p_reopen_date
            )
        FOR UPDATE OF appointment
    ),
    cancelled AS (
        UPDATE public.appointment AS appointment
        SET status = 'cancelled',
            admin_notes = 'تم إلغاء الحجز بسبب اعتذار الطبيب عن الحضور.'
        FROM eligible
        WHERE appointment.appointment_id = eligible.appointment_id
        RETURNING appointment.appointment_id, appointment.user_id
    ),
    created_notifications AS (
        INSERT INTO public.notifications (user_id, title, message, type, data)
        SELECT
            cancelled.user_id,
            'تم إلغاء موعدك الطبي',
            'نعتذر، تم إلغاء موعدك مع الطبيب بسبب تعذر حضوره. يمكنك حجز موعد آخر لاحقًا.',
            'appointment',
            jsonb_build_object(
                'appointment_id', cancelled.appointment_id,
                'doctor_id', v_doctor_id,
                'type', 'appointment_cancelled',
                'screen', '/appointments/my-appointments'
            )
        FROM cancelled
        JOIN eligible
            ON eligible.appointment_id = cancelled.appointment_id
            AND eligible.user_id = cancelled.user_id
        RETURNING notification_id, user_id, data
    ),
    queued AS (
        INSERT INTO public.doctor_booking_notification_outbox (
            appointment_id,
            user_id,
            doctor_id,
            notification_id,
            channel,
            phone_number,
            notification_data
        )
        SELECT
            cancelled.appointment_id,
            cancelled.user_id,
            v_doctor_id,
            created_notifications.notification_id,
            delivery.channel,
            eligible.phone_number,
            created_notifications.data
        FROM created_notifications
        JOIN cancelled
            ON cancelled.appointment_id =
                (created_notifications.data ->> 'appointment_id')::bigint
            AND cancelled.user_id = created_notifications.user_id
        JOIN eligible
            ON eligible.appointment_id = cancelled.appointment_id
            AND eligible.user_id = cancelled.user_id
        CROSS JOIN (VALUES ('push'::text), ('sms'::text)) AS delivery(channel)
        ON CONFLICT (appointment_id, channel) DO NOTHING
        RETURNING outbox_id
    )
    SELECT
        (SELECT count(*) FROM cancelled),
        (SELECT count(*) FROM queued)
    INTO v_cancelled_count, v_queued_count;

    RETURN jsonb_build_object(
        'doctor_id', v_doctor_id,
        'is_booking_open', false,
        'booking_reopen_at', v_booking_reopen_at,
        'cancelled_appointments_count', v_cancelled_count,
        'notifications_queued_count', v_queued_count
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.create_appointment_with_booking_lock(
    p_appointment jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_doctor_id bigint;
    v_doctor_status text;
    v_doctor_hidden boolean;
    v_is_booking_open boolean;
    v_booking_reopen_at timestamptz;
    v_schedule_status text;
    v_schedule_day text;
    v_schedule_max_patients integer;
    v_doctor_fee numeric;
    v_platform_fee numeric;
    v_appointment_date date;
    v_today date := (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Aden')::date;
    v_expected_day text;
    v_appointment jsonb;
BEGIN
    -- 1. Lock the same Doctor row used by toggle_doctor_booking.
    SELECT
        doctor.doctor_id,
        doctor.status,
        doctor.is_hidden,
        doctor.is_booking_open,
        doctor.booking_reopen_at
    INTO
        v_doctor_id,
        v_doctor_status,
        v_doctor_hidden,
        v_is_booking_open,
        v_booking_reopen_at
    FROM public.doctor_schedule AS schedule
    JOIN public.doctor AS doctor
        ON doctor.doctor_id = schedule.doctor_id
    WHERE schedule.schedule_id = (p_appointment ->> 'schedule_id')::bigint
    FOR UPDATE OF doctor;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'APPOINTMENT_SCHEDULE_NOT_FOUND';
    END IF;

    -- 2. Lock the schedule after the Doctor to keep booking lock order stable.
    SELECT schedule.status, schedule.day_of_week, schedule.max_patients
    INTO v_schedule_status, v_schedule_day, v_schedule_max_patients
    FROM public.doctor_schedule AS schedule
    WHERE schedule.schedule_id = (p_appointment ->> 'schedule_id')::bigint
        AND schedule.doctor_id = v_doctor_id
    FOR UPDATE;

    IF NOT FOUND OR v_schedule_status <> 'active' THEN
        RAISE EXCEPTION 'APPOINTMENT_SCHEDULE_UNAVAILABLE';
    END IF;

    IF v_doctor_hidden OR v_doctor_status <> 'active' THEN
        RAISE EXCEPTION 'APPOINTMENT_DOCTOR_UNAVAILABLE';
    END IF;

    v_appointment_date := (p_appointment ->> 'appointment_date')::date;

    IF v_appointment_date < v_today OR v_appointment_date > v_today + 7 THEN
        RAISE EXCEPTION 'APPOINTMENT_DATE_INVALID';
    END IF;

    v_expected_day := CASE EXTRACT(DOW FROM v_appointment_date)::integer
        WHEN 0 THEN 'الاحد'
        WHEN 1 THEN 'الاثنين'
        WHEN 2 THEN 'الثلاثاء'
        WHEN 3 THEN 'الاربعاء'
        WHEN 4 THEN 'الخميس'
        WHEN 5 THEN 'الجمعة'
        WHEN 6 THEN 'السبت'
    END;

    IF replace(replace(trim(v_schedule_day), 'أ', 'ا'), 'إ', 'ا') <> v_expected_day THEN
        RAISE EXCEPTION 'APPOINTMENT_SCHEDULE_DAY_INVALID';
    END IF;

    -- 3. Validate the selected department and relation from the locked schedule.
    IF NOT EXISTS (
        SELECT 1
        FROM public.department AS department
        JOIN public.doctor_department AS doctor_department
            ON doctor_department.depart_id = department.depart_id
        WHERE department.depart_id = (p_appointment ->> 'depart_id')::bigint
            AND doctor_department.doctor_id = v_doctor_id
            AND (
                NOT (to_jsonb(department) ? 'status')
                OR to_jsonb(department) ->> 'status' = 'active'
            )
            AND (
                NOT (to_jsonb(department) ? 'is_active')
                OR to_jsonb(department) ->> 'is_active' IN ('true', 'active')
            )
    ) THEN
        RAISE EXCEPTION 'APPOINTMENT_DEPARTMENT_INVALID';
    END IF;

    -- 4. Automatically reopen elapsed temporary suspensions before insertion.
    IF NOT COALESCE(v_is_booking_open, true)
        AND v_booking_reopen_at IS NOT NULL
        AND v_booking_reopen_at <= CURRENT_TIMESTAMP THEN
        UPDATE public.doctor
        SET is_booking_open = true,
            booking_reopen_at = NULL
        WHERE doctor_id = v_doctor_id;

        v_is_booking_open := true;
    END IF;

    IF NOT COALESCE(v_is_booking_open, true) THEN
        RAISE EXCEPTION 'DOCTOR_BOOKING_CLOSED';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.appointment AS appointment
        WHERE appointment.schedule_id = (p_appointment ->> 'schedule_id')::bigint
            AND appointment.appointment_date = v_appointment_date
            AND appointment.patient_phone = p_appointment ->> 'patient_phone'
            AND appointment.patient_name = p_appointment ->> 'patient_name'
    ) THEN
        RAISE EXCEPTION 'APPOINTMENT_DUPLICATE';
    END IF;

    IF (
        SELECT count(*)
        FROM public.appointment AS appointment
        WHERE appointment.schedule_id = (p_appointment ->> 'schedule_id')::bigint
            AND appointment.appointment_date = v_appointment_date
            AND appointment.status IN ('pending', 'approved')
    ) >= v_schedule_max_patients THEN
        RAISE EXCEPTION 'APPOINTMENT_CAPACITY_REACHED';
    END IF;

    SELECT doctor.consultation_fee
    INTO v_doctor_fee
    FROM public.doctor AS doctor
    WHERE doctor.doctor_id = v_doctor_id;

    v_platform_fee := COALESCE((p_appointment ->> 'platform_fee')::numeric, 0);

    INSERT INTO public.appointment AS appointment (
        user_id,
        schedule_id,
        depart_id,
        patient_name,
        patient_phone,
        patient_age,
        patient_gender,
        notes,
        payment_receipt,
        appointment_date,
        doctor_fee,
        platform_fee,
        total_amount,
        status,
        admin_notes,
        created_at
    )
    VALUES (
        (p_appointment ->> 'user_id')::bigint,
        (p_appointment ->> 'schedule_id')::bigint,
        (p_appointment ->> 'depart_id')::bigint,
        p_appointment ->> 'patient_name',
        p_appointment ->> 'patient_phone',
        (p_appointment ->> 'patient_age')::integer,
        p_appointment ->> 'patient_gender',
        p_appointment ->> 'notes',
        p_appointment ->> 'payment_receipt',
        v_appointment_date,
        v_doctor_fee,
        v_platform_fee,
        v_doctor_fee + v_platform_fee,
        'pending',
        NULL,
        CURRENT_TIMESTAMP
    )
    RETURNING to_jsonb(appointment) INTO v_appointment;

    RETURN v_appointment;
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_doctor_booking_notification_tasks(
    p_limit integer DEFAULT 50
)
RETURNS TABLE (
    outbox_id bigint,
    appointment_id bigint,
    user_id bigint,
    doctor_id bigint,
    channel text,
    phone_number text,
    notification_data jsonb,
    attempts integer
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    RETURN QUERY
    WITH claimable AS (
        SELECT outbox.outbox_id
        FROM public.doctor_booking_notification_outbox AS outbox
        WHERE (
            outbox.status = 'pending'
            AND outbox.available_at <= CURRENT_TIMESTAMP
        ) OR (
            outbox.status = 'processing'
            AND outbox.locked_at <= CURRENT_TIMESTAMP - INTERVAL '10 minutes'
        )
        ORDER BY outbox.available_at, outbox.outbox_id
        FOR UPDATE SKIP LOCKED
        LIMIT GREATEST(1, LEAST(COALESCE(p_limit, 50), 100))
    )
    UPDATE public.doctor_booking_notification_outbox AS outbox
    SET status = 'processing',
        locked_at = CURRENT_TIMESTAMP,
        lease_token = md5(
            outbox.outbox_id::text
            || clock_timestamp()::text
            || random()::text
        ),
        attempts = outbox.attempts + 1
    FROM claimable
    WHERE outbox.outbox_id = claimable.outbox_id
    RETURNING
        outbox.outbox_id,
        outbox.appointment_id,
        outbox.user_id,
        outbox.doctor_id,
        outbox.channel,
        outbox.phone_number,
        outbox.notification_data || jsonb_build_object(
            '_lease_token',
            outbox.lease_token
        ),
        outbox.attempts;
END;
$$;

